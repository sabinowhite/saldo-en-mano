import * as SQLite from 'expo-sqlite';
import * as SecureStore from 'expo-secure-store';
import { getRandomBytesAsync } from 'expo-crypto';
import { File } from 'expo-file-system';
import { createRepository, migrateDatabase } from './repository';
import type { FinanceRepository } from './repository';
import { StorageError } from './errors';
import { loadDatabaseKey, assertCipherAvailable } from './key';
import { databaseDirectoryUri } from './file-uri';

const DATABASE_NAME = 'saldo-en-mano.db';
const KEY_NAME = 'saldo-en-mano.database-key.v1';
const KEY_OPTIONS = { keychainService: 'com.sabinowhite.saldoenmano.database', keychainAccessible: SecureStore.WHEN_UNLOCKED_THIS_DEVICE_ONLY };
let connection: Promise<FinanceRepository> | null = null;
async function atStage<T>(stage: NonNullable<ConstructorParameters<typeof StorageError>[1]>, task: () => Promise<T> | T): Promise<T> {
  try { return await task(); }
  catch (error) { if (error instanceof StorageError) throw error; throw new StorageError('unavailable', stage); }
}
async function connect(): Promise<FinanceRepository> {
  if (!await atStage('almacen-seguro', () => SecureStore.isAvailableAsync())) throw new StorageError('unavailable', 'almacen-seguro');
  // Probe in memory before creating a file or key. Unknown pragmas silently do
  // nothing on plain SQLite, so setting PRAGMA key alone is not a safety check.
  const probe = await atStage('prueba-cifrado', () => SQLite.openDatabaseAsync(':memory:'));
  try {
    const cipher = await atStage('prueba-cifrado', () => probe.getFirstAsync<{ cipher_version: string }>('PRAGMA cipher_version'));
    assertCipherAvailable(cipher);
  } finally { await atStage('prueba-cifrado', () => probe.closeAsync()); }
  const databaseExists = await atStage('ruta-base', () => new File(databaseDirectoryUri(SQLite.defaultDatabaseDirectory), DATABASE_NAME).exists);
  const key = await atStage('clave-base', () => loadDatabaseKey({
    get: () => SecureStore.getItemAsync(KEY_NAME, KEY_OPTIONS),
    set: value => SecureStore.setItemAsync(KEY_NAME, value, KEY_OPTIONS),
  }, databaseExists, () => getRandomBytesAsync(32)));
  const db = await atStage('abrir-base', () => SQLite.openDatabaseAsync(DATABASE_NAME));
  try {
    // Only fixed hex generated by the CSPRNG reaches this pragma; never user text.
    await db.execAsync(`PRAGMA key = '${key}'`);
    const check = await db.getFirstAsync<{ quick_check: string }>('PRAGMA quick_check');
    if (check?.quick_check !== 'ok') throw new StorageError('corrupt-data');
    await migrateDatabase(db);
    await db.execAsync('PRAGMA journal_mode = WAL; PRAGMA synchronous = FULL; PRAGMA cipher_memory_security = ON;');
    return createRepository(db);
  } catch (error) {
    await db.closeAsync().catch(() => undefined);
    if (error instanceof StorageError) throw error;
    throw new StorageError('corrupt-data');
  }
}
export function openRepository(): Promise<FinanceRepository> {
  if (!connection) connection = connect().catch(error => { connection = null; throw error; });
  return connection;
}
